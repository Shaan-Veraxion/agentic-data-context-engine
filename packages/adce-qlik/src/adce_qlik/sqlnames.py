"""Column names a database returns for a query's select list, as Qlik sees them.

Oracle stores and returns unquoted identifiers (column names and aliases) in upper case; quoted ones keep their
case. So "SELECT t.effective_from, x AS id" reaches Qlik as EFFECTIVE_FROM and ID. Other dialects keep the names
as written here; for unaliased columns the real casing comes from the table definition, which is not known.
An unaliased expression (a + b) gets a name generated by the database: reported as None.
"""
from __future__ import annotations

from sqlglot import exp
from sqlglot.expressions.core import Expr as SqlExpr

UPPER_FOLDING = {"oracle"}


def output_name(e: SqlExpr, dialect: str | None) -> str | None:
    """Name of one select-list item, or None when the database generates it."""
    if isinstance(e, exp.Star):
        return "*"
    ident = e.args.get("alias") if isinstance(e, exp.Alias) else None
    if ident is None:
        inner = e.unalias()
        if isinstance(inner, exp.Column):
            if isinstance(inner.this, exp.Star):
                return "*"
            ident = inner.this
        else:
            return None
    name = ident.name
    if dialect in UPPER_FOLDING and not ident.quoted:
        return name.upper()
    return name
