"""Embedded source SQL written for the database behind a Qlik connection, converted to Dremio SQL.

A Qlik app may query its databases directly (Oracle, SQL Server, ...) instead of through Dremio. Each such
connection is described in the app's connections.toml:

    ["TITAN SE20"]
    dialect = "oracle"            # sqlglot dialect of the queries sent through this connection
    dremio_source = "titan"       # Dremio source the database is mounted as
    default_schema = "FIN"        # schema (or "database.schema") of tables the queries name without one

The query is parsed in its dialect and rendered as Dremio SQL (sqlglot), with these corrections:
- string-to-date parsing is written as Dremio TO_DATE / TO_TIMESTAMP with Dremio format codes
- source functions sqlglot keeps unchanged but Dremio lacks are rewritten where an equivalent exists
  (Oracle RAWTOHEX(raw) -> UPPER(TO_HEX(raw)))
- a function sqlglot does not know in the source dialect is reported untranslatable, never passed through
- output columns are given the names the source database returns (Oracle: unquoted names in upper case), as
  explicit quoted aliases, so the names Qlik saw do not depend on how Dremio names columns
Table names get the Dremio source and default schema prepended.
"""
from __future__ import annotations

import tomllib
from dataclasses import dataclass
from pathlib import Path

from adce_qlik.sqlnames import UPPER_FOLDING, output_name
from sqlglot import exp
from sqlglot.dialects.dremio import Dremio
from sqlglot.expressions.core import Expr as SqlExpr
from sqlglot.time import format_time

from .expressions import Untranslatable


@dataclass
class Connection:
    dialect: str = "dremio"
    dremio_source: str | None = None
    default_schema: str | None = None


def load_connections(path: str | Path) -> dict[str, Connection]:
    p = Path(path)
    if not p.exists():
        return {}
    data = tomllib.loads(p.read_text(encoding="utf-8"))
    return {name: Connection(**cfg) for name, cfg in data.items()}


def _dremio_format(fmt: SqlExpr | None) -> SqlExpr | None:
    if not isinstance(fmt, exp.Literal) or not fmt.is_string:
        return None
    converted = format_time(fmt.this, Dremio.INVERSE_TIME_MAPPING)
    return exp.Literal.string(converted.upper()) if converted else None


def _fix_dates(node: SqlExpr) -> SqlExpr:
    if isinstance(node, (exp.StrToDate, exp.TsOrDsToDate, exp.StrToTime)) and node.args.get("format") is not None:
        fmt = _dremio_format(node.args["format"])
        if fmt is None:
            raise Untranslatable(f"date parsing with a non-literal format: {node.sql()}", "T2")
        fn = "TO_TIMESTAMP" if isinstance(node, exp.StrToTime) else "TO_DATE"
        return exp.Anonymous(this=fn, expressions=[node.this, fmt])
    return node


_DREMIO_FUNCS = {"TO_DATE", "TO_TIMESTAMP", "TO_HEX"}  # written by this module, valid in Dremio


def _rawtohex(args: list[SqlExpr]) -> SqlExpr:
    return exp.Upper(this=exp.Anonymous(this="TO_HEX", expressions=args))


_REWRITES = {"oracle": {"RAWTOHEX": _rawtohex}}


def _name_outputs(body: SqlExpr, dialect: str) -> None:
    """Alias each output column with the name the source database returns (the first SELECT names a UNION)."""
    sel = body
    while isinstance(sel, exp.SetOperation):
        sel = sel.this
    if not isinstance(sel, exp.Select):
        return
    items = []
    for e in sel.expressions:
        name = output_name(e, dialect)
        if name is None:
            raise Untranslatable(f"column name generated by the {dialect} database for: {e.sql(dialect=dialect)}",
                                 "T1")
        items.append(e if name == "*" else exp.alias_(e.unalias(), name, quoted=True))
    sel.set("expressions", items)


def to_dremio(body: SqlExpr, dialect: str | None, conn: Connection | None) -> SqlExpr:
    """body: the embedded query parsed in `dialect` (None: Dremio). Returns the Dremio version."""
    if dialect in UPPER_FOLDING:
        _name_outputs(body, dialect)
    body = body.transform(_fix_dates)
    rewrites = _REWRITES.get(dialect or "", {})
    if rewrites:
        body = body.transform(lambda n: rewrites[n.name.upper()](list(n.expressions))
                              if isinstance(n, exp.Anonymous) and n.name.upper() in rewrites else n)
    if dialect and dialect != "dremio":
        unknown = sorted({f.name.upper() for f in body.find_all(exp.Anonymous)} - _DREMIO_FUNCS)
        if unknown:
            raise Untranslatable(f"source SQL ({dialect}) uses functions with no Dremio translation: "
                                 f"{', '.join(unknown)}", "T2")
    if conn is None or not conn.dremio_source:
        return body
    local = {c.alias_or_name for c in body.find_all(exp.CTE)}
    prefix = [conn.dremio_source]

    def path(node: SqlExpr) -> SqlExpr:
        if not isinstance(node, exp.Table) or not node.name or (not node.db and node.name in local):
            return node
        parts = [p.name for p in node.parts]
        if len(parts) == 1 and conn.default_schema:
            parts = conn.default_schema.split(".") + parts
        new = exp.to_table(".".join(f'"{p}"' for p in prefix + parts), dialect="dremio")
        new.set("alias", node.args.get("alias"))
        return new

    return body.transform(path)
