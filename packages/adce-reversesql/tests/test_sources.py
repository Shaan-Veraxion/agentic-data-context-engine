"""Embedded SQL written for the database behind a connection (Oracle, SQL Server), converted to Dremio SQL."""
import pytest
import sqlglot
from adce_qlik import read_script
from adce_qlik.model import build_app
from adce_reversesql.compose import compose
from adce_reversesql.expressions import Untranslatable
from adce_reversesql.sources import Connection, load_connections, to_dremio


def dremio(sql: str, dialect: str, conn: Connection | None = None) -> str:
    return to_dremio(sqlglot.parse_one(sql, read=dialect), dialect, conn).sql(dialect="dremio")


def test_oracle_dates_rawtohex_and_paths():
    conn = Connection(dialect="oracle", dremio_source="titan", default_schema="FIN")
    out = dremio("SELECT rawtohex(ID) AS ID FROM V WHERE E > SYSDATE AND D >= TO_DATE('01-04-2025', 'DD-MM-YYYY')",
                 "oracle", conn)
    assert out == ('SELECT UPPER(TO_HEX(ID)) AS "ID" FROM "titan"."FIN"."V" '
                   "WHERE E > CURRENT_TIMESTAMP() AND D >= TO_DATE('01-04-2025', 'DD-MM-YYYY')")


def test_sql_server_qualified_names_keep_their_schema():
    conn = Connection(dialect="tsql", dremio_source="pluto", default_schema="Pluto.dbo")
    out = dremio("SELECT a AS 'A b' FROM Pluto.dbo.T1, T2", "tsql", conn)
    assert out == 'SELECT a AS "A b" FROM "pluto"."Pluto"."dbo"."T1", "pluto"."Pluto"."dbo"."T2"'


def test_unknown_source_function_is_reported_not_passed_through():
    with pytest.raises(Untranslatable, match="SOME_ORACLE_FN"):
        dremio("SELECT some_oracle_fn(x) FROM t", "oracle")


def test_connections_file_drives_parse_and_translate(tmp_path):
    (tmp_path / "connections.toml").write_text('["Ora"]\ndialect = "oracle"\ndremio_source = "ora"\n')
    conns = load_connections(tmp_path / "connections.toml")
    app = build_app(read_script("t", {"s.qvs": "LIB CONNECT TO 'Ora';\nT: SQL SELECT NVL(a, 0) AS a FROM S.V;\n"}),
                    connection_dialects={k: c.dialect for k, c in conns.items()})
    t = compose(app, connections=conns)
    sql = t.table_sql("T")
    assert t.tables["T"].complete and sql is not None
    assert 'COALESCE(a, 0) AS "A"' in sql and 'FROM "ora"."S"."V"' in sql
    assert app.tables["T"].fields == ["A"]  # Oracle returns the unquoted alias in upper case


def test_oracle_output_names_are_the_ones_oracle_returns():
    out = dremio('SELECT t.effective_from, x AS id, y "Mixed", z w FROM v t', "oracle")
    assert out == 'SELECT t.effective_from AS "EFFECTIVE_FROM", x AS "ID", y AS "Mixed", z AS "W" FROM v AS t'
    with pytest.raises(Untranslatable, match="generated by the oracle database"):
        dremio("SELECT a + b FROM v", "oracle")
    assert dremio("SELECT t.effective_from FROM v t", "tsql") == "SELECT t.effective_from FROM v AS t"  # as written
